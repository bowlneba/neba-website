
using ErrorOr;

using Neba.Api.Domain;
using Neba.Api.Features.Bowlers.Domain;
using Neba.Api.Features.Storage.Domain;

namespace Neba.Api.Features.HallOfFame.Domain;

/// <summary>
/// Represents an induction into the Hall of Fame.
/// </summary>
/// <remarks>
/// This entity is the domain root for a Hall of Fame entry and
/// uses a strongly-typed <see cref="HallOfFameId"/> (ULID) as its identifier.
/// Keep business logic for induction events and rules on this entity.
/// </remarks>
public sealed class HallOfFameInduction
    : AggregateRoot
{
    /// <summary>
    /// The unique identifier for this Hall of Fame induction.
    /// This is a strongly-typed ULID-based id generated by the
    /// <c>StronglyTypedIds</c> source generator using the format "ulid-full".
    /// Use this type instead of raw strings to ensure type-safety across the domain.
    /// </summary>
    public HallOfFameId Id { get; init; }

    /// <summary>
    /// The year the induction took place.
    /// </summary>
    public int Year { get; init; }

    /// <summary>
    /// The identifier of the bowler associated with this induction.
    /// This is a reference to the <see cref="Bowler"/> entity in the Bowlers bounded context.
    /// Use this ID for external references instead of the navigation property to avoid cross-context coupling.
    /// </summary>
    public BowlerId BowlerId { get; init; }

    /// <summary>
    /// The bowler associated with this induction.
    /// This is a reference to the <see cref="Bowler"/> entity in the Bowlers bounded context.
    /// This property is internal to prevent cross-context references from outside the domain layer.
    /// Use the Bowler's ID or other value objects for external references instead.
    /// Keep this as a navigation property for internal use within the Hall of Fame context.
    /// </summary>
    internal Bowler Bowler { get; init; } = null!;

    /// <summary>
    /// The categories associated with this induction.
    /// </summary>
    public IReadOnlyCollection<HallOfFameCategory> Categories { get; internal set; } = [];

    /// <summary>
    /// An optional photo associated with the induction, such as a picture of the bowler receiving the award or a commemorative image. This is represented as a <see cref="StoredFile"/> value object, which contains information about the file's storage location, content type, and other relevant metadata. This allows for flexible handling of associated media while keeping the core induction data focused on the essential attributes of the Hall of Fame entry.
    /// </summary>
    public StoredFile? Photo { get; private set; }

    /// <summary>
    /// The point and zoom of <see cref="Photo"/> kept in frame in round avatars. Null when <see cref="Photo"/> is null, and for photos saved before framing existed (treat as <see cref="PhotoFocalPoint.Default"/>).
    /// </summary>
    public PhotoFocalPoint? PhotoFocalPoint { get; private set; }

    /// <summary>
    /// Sets the photo and its focal point and zoom together.
    /// </summary>
    /// <param name="photo">The stored photo.</param>
    /// <param name="focalX">Percent from the left edge, 0 to 100.</param>
    /// <param name="focalY">Percent from the top edge, 0 to 100.</param>
    /// <param name="zoom">Zoom in percent, 100 to 300.</param>
    public ErrorOr<Success> SetPhoto(StoredFile photo, int focalX, int focalY, int zoom)
    {
        ArgumentNullException.ThrowIfNull(photo);

        var focalPoint = PhotoFocalPoint.Create(focalX, focalY, zoom);
        if (focalPoint.IsError)
        {
            return focalPoint.Errors;
        }

        Photo = photo;
        PhotoFocalPoint = focalPoint.Value;
        return Result.Success;
    }

    /// <summary>
    /// Removes the photo and its focal point. Does nothing when there is no photo.
    /// </summary>
    public void ClearPhoto()
    {
        Photo = null;
        PhotoFocalPoint = null;
    }

    /// <summary>
    /// Moves the focal point and changes the zoom of the current photo.
    /// </summary>
    /// <param name="x">Percent from the left edge, 0 to 100.</param>
    /// <param name="y">Percent from the top edge, 0 to 100.</param>
    /// <param name="zoom">Zoom in percent, 100 to 300.</param>
    public ErrorOr<Success> SetFocalPoint(int x, int y, int zoom)
    {
        if (Photo is null)
        {
            return HallOfFameErrors.NoPhoto;
        }

        var focalPoint = PhotoFocalPoint.Create(x, y, zoom);
        if (focalPoint.IsError)
        {
            return focalPoint.Errors;
        }

        PhotoFocalPoint = focalPoint.Value;
        return Result.Success;
    }
}